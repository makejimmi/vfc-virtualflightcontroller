#define ISR_PRIORITY_MASTER_TX      50
#define ISR_PRIORITY_MASTER_RX      51
#define ISR_PRIORITY_MASTER_ER      52

#define MASTER_CHANNEL_BAUDRATE     10000000         /* Master channel baud rate                                     */

