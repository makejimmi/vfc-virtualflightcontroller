IFX_INTERRUPT(masterTxISR, 0, ISR_PRIORITY_MASTER_TX);                  /* SPI Master ISR for transmit data         */
IFX_INTERRUPT(masterRxISR, 0, ISR_PRIORITY_MASTER_RX);                  /* SPI Master ISR for receive data          */
IFX_INTERRUPT(masterErISR, 0, ISR_PRIORITY_MASTER_ER);                  /* SPI Master ISR for error                 */

void masterTxISR()
{
    IfxCpu_enableInterrupts();
    IfxQspi_SpiMaster_isrTransmit(&spi);
}

void masterRxISR()
{
    IfxCpu_enableInterrupts();
    IfxQspi_SpiMaster_isrReceive(&spi);
}

void masterErISR()
{
    IfxCpu_enableInterrupts();
    IfxQspi_SpiMaster_isrError(&spi);
}


void tc275_spi_init(void) {
    IfxQspi_SpiMaster_Config conf;
    IfxQspi_SpiMaster_initModuleConfig(&conf, &MODULE_QSPI1); // Default config - Master, braucht noch Pins und INT Prio

    const IfxQspi_SpiMaster_Pins pins = {
        &IfxQspi1_SCLK_P10_2_OUT, IfxPort_OutputMode_pushPull,          /* SCLK Pin                       (CLK)     */
        &IfxQspi1_MTSR_P10_3_OUT, IfxPort_OutputMode_pushPull,          /* MasterTransmitSlaveReceive pin (MOSI)    */
        &IfxQspi1_MRSTA_P10_1_IN, IfxPort_InputMode_pullUp,           /* MasterReceiveSlaveTransmit pin (MISO)    */
        IfxPort_PadDriver_cmosAutomotiveSpeed3
    };
    conf.pins = &pins;

    conf.txPriority = ISR_PRIORITY_MASTER_TX;
    conf.rxPriority = ISR_PRIORITY_MASTER_RX;
    conf.erPriority = ISR_PRIORITY_MASTER_ER;
    conf.isrProvider = IfxSrc_Tos_cpu2;

    IfxQspi_SpiMaster_initModule(&spi, &conf);


    IfxQspi_SpiMaster_ChannelConfig ch_conf;
    IfxQspi_SpiMaster_initChannelConfig(&ch_conf, &spi);

    ch_conf.ch.baudrate = MASTER_CHANNEL_BAUDRATE;
    ch_conf.ch.mode.shiftClock =IfxQspi_ShiftClock_shiftTransmitDataOnTrailingEdge;

    const IfxQspi_SpiMaster_Output slaveselect = {
            &IfxQspi1_SLSO9_P10_5_OUT, IfxPort_OutputMode_pushPull,
            IfxPort_PadDriver_cmosAutomotiveSpeed1
    };
    ch_conf.sls.output = slaveselect;

    IfxQspi_SpiMaster_initChannel(&spiChannel, &ch_conf);
}

void spi_write ( uint8_t *data_buf, uint8_t len ) {
    uint8_t tx_buf[ 265 ];
    uint8_t cnt;

    for ( cnt = 0; cnt < len; cnt++ )
    {
        tx_buf[ cnt ] = data_buf[ cnt ];
    }

    while( IfxQspi_SpiMaster_getStatus(&spiChannel) == IfxQspi_Status_busy )
        { ; }

    IfxQspi_SpiMaster_exchange(&spiChannel, &tx_buf[0], NULL, len);

    while( IfxQspi_SpiMaster_getStatus(&spiChannel) == IfxQspi_Status_busy )
        { ; }
}

void pressure5_spi_write ( uint8_t reg, uint8_t *data_buf, uint8_t len )
{
    uint8_t tx_buf[ 265 ];
    uint8_t cnt;

    tx_buf[ 0 ] = reg;
    for ( cnt = 1; cnt <= len; cnt++ )
    {
        tx_buf[ cnt ] = data_buf[ cnt - 1 ];
    }

    while( IfxQspi_SpiMaster_getStatus(&spiChannel) == IfxQspi_Status_busy )
        { ; }

    IfxQspi_SpiMaster_exchange(&spiChannel, &tx_buf[0], NULL, len+1);
}

void pressure5_spi_read ( uint8_t reg, uint8_t *data_buf, uint8_t len )
{
    uint8_t tx_buf[ 32 ];
    uint8_t read_buf[ 256 ] = { 0 };
    uint16_t cnt;

    tx_buf[ 0 ] = reg | 0x80; // READ COMMAND
    tx_buf[ 1 ] = 0x00;
    tx_buf[ 2 ] = 0x00;

    while( IfxQspi_SpiMaster_getStatus(&spiChannel) == IfxQspi_Status_busy )
        { ; }

    IfxQspi_SpiMaster_exchange(&spiChannel, tx_buf, read_buf, len+2);

    while( IfxQspi_SpiMaster_getStatus(&spiChannel) == IfxQspi_Status_busy )
        { ; }

    for ( cnt = 2; cnt <= len+2; cnt++ )
    {
        *data_buf = read_buf[ cnt ];
        data_buf++;
    }
}
