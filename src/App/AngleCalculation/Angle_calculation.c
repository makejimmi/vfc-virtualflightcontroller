float angle_calc_get_yaw(ImuData_t imu_data) {
    return 0.0;
}


/**
 * \brief Calculates all the angles
 *
 * Takes the imu data in ms2 and calculates the angels, using the
 * complemtary filter function for roll and pitch, and
 * another one for yaw
 * Input: imu_data with accelartion and gyro data
 * output: angles
 */
OrientationData_t angle_calc(ImuData_t imu_data) {
    OrientationData_t temp = angle_calc_complementary_filter(imu_data);
    temp.yaw = angle_calc_get_yaw(imu_data);
    return temp;
}



