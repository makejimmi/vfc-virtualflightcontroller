/**
 * \brief Simple wait function
 *
 * This function gets called after every time after taking sample from CPU0. is not strictly
 * necessary, but still good practice
 * the time itself is defined in header file
 */
void angle_calc_wait_sample_time(void) {
    waitTime(IfxStm_getTicksFromMilliseconds(BSP_DEFAULT_TIMER, ANGLE_CALC_SAMPLE_TIME_MS));
}


/**
 * \brief Calculates the roll and pitch angles
 *
 * Takes the imu data in ms2 and calculates the angels, first in rad and
 * then in grads. The yaw angle is NOT calculated in this, see calc_yaw
 * Input: imu_data with accelartion and gyro data
 * output: angles, from with yaw is always 0
 */
OrientationData_t angle_calc_complementary_filter(ImuData_t imu_data) {
    OrientationData_t temp;

    temp.roll  = atan2(imu_data.accel_y, imu_data.accel_z);
    temp.roll = temp.roll * (180.0/PI);
    temp.pitch = atan2( (-1.0)*imu_data.accel_x, sqrt( pow(imu_data.accel_y, 2) + pow(imu_data.accel_z, 2) ) );
    temp.pitch = temp.pitch * (180.0/PI);
    temp.yaw   = 0.0;

    return temp;
}


